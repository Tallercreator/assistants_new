export type AssistantRole = "smt" | "assistant";
/** Колонка матрицы: 0 — создание и просмотр моих заявок, 1 — согласование заявок сотрудников. */
export type RightColumn = 0 | 1;
type Pair = [number, number];

export type RequestType = {
  title: string;
  /** Доступность [создание, согласование] для роли «Ассистент SMT». */
  smt: Pair;
  /** Доступность [создание, согласование] для роли «Ассистент». */
  assistant: Pair;
  /** Просмотр заявки руководителя выдаётся автоматически: только SMT или обеим ролям. */
  view?: "smt" | "both";
  subtitle?: string;
};

export type RequestGroup = {
  title: string;
  types: RequestType[];
  /** false — права выдаются сразу на всю группу, заявки не раскрываются (Командировки). */
  expandable?: boolean;
};

/** rights[группа][заявка][колонка] */
export type Rights = boolean[][][];

const R = (title: string, smt: Pair, assistant: Pair, extra: Partial<RequestType> = {}) => ({
  title,
  smt,
  assistant,
  ...extra,
});

